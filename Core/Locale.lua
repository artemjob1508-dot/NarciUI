local current = nil

local reverse

function NS.LSource(text)
    if not current then return text end
    if not reverse or reverse.forTable ~= current then
        reverse = { forTable = current, map = {} }
        for source, translated in pairs(current) do
            if not reverse.map[translated] then reverse.map[translated] = source end
        end
    end
    return reverse.map[text] or text
end

NS.L = setmetatable({}, {
    __index = function(_, key)
        if current then
            local text = current[key]
            if text then return text end
        end
        return key
    end,
    __newindex = function()
        error("NS.L — таблица только для чтения")
    end,
})

